; Function: saa_wleb128s
;
; Description: Write signed LEB128 value to SAA
;
; C Declaration: void saa_wleb128s(struct SAA *psaa, int value)
;
; Input (Stack): [EBP+8]  = *psaa
;                [EBP+12] = value
;
; Output: none
;
; Modified Registers: EAX, ECX, (EDX)
; ---------------------------------------------------------------------------

