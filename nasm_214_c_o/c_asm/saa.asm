%assign len      -58h
%assign size     -54h
%assign negative -50h
%assign more     -4Ch
%assign byte     -45h
%assign ptemp    -44h
%assign temp     -40h
%assign psaa      8
%assign value     0Ch

saa_wleb128s:
                push    ebp
                mov     ebp, esp
                sub     esp, 92         ; char temp[64], *ptemp;
                nop                     ; uint8_t byte;
                lea     eax, [ebp+temp]
                mov     [ebp+ptemp], eax ; ptemp = temp;
                mov     eax, 1          ; bool more, negative;
                mov     [ebp+more], eax ; more = 1;
                mov     eax, [ebp+value] ; int size, len;
                cmp     eax, 0
                mov     eax, 0
                setl    al
                mov     [ebp+negative], eax ; negative = (value < 0);
                mov     eax, 32         ; sizeof(int) * 8 = 32
                mov     [ebp+size], eax ; size = sizeof(int) * 8;
                mov     eax, 0
                mov     [ebp+len], eax  ; len = 0;

swls_1:                                 ; ...
                mov     eax, [ebp+more] ; while (more) {
                cmp     eax, 0
                jz      swls_9
                ;mov    eax, [ebp+value]
                ;and    eax, 7Fh        ; byte = value & 0x7f;
                mov     al, [ebp+value]
                and     al, 7Fh        ; byte = value & 0x7f;
                mov     [ebp+byte], al
                mov     eax, [ebp+value]
                sar     eax, 7
                mov     [ebp+value], eax ; value >>= 7;
                mov     eax, [ebp+negative]
                cmp     eax, 0          ; if (negative)
                jz      swls_2
                mov     eax, [ebp+size] ; /* sign extend */
                sub     eax, 7          ; (size - 7)
                mov     ecx, 1
                mov     [ebp+tmp], ecx
                mov     ecx, eax
                mov     eax, [ebp+tmp]
                shl     eax, cl
                mov     ecx, 0
                sub     ecx, eax        ; neg
                mov     eax, [ebp+value]
                or      eax, ecx
                mov     [ebp+value], eax ; value |= -(1 << (size - 7));

swls_2:                                 ; ...
                mov     eax, [ebp+value] ; /* sign bit of byte is second high order bit (0x40) */
                cmp     eax, 0          ; if ((value == 0 && !(byte & 0x40)) ||
