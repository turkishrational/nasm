                jmp     swls_8
; ---------------------------------------------------------------------------

swls_7:                                 ; ...
                ;movzx  eax, byte [ebp+byte] ; else
                ;or     eax, 80h
                mov     al, [ebp+byte] ; else
                or      al, 80h
                mov     [ebp+byte], al  ; byte |= 0x80;

swls_8:                                 ; ...
